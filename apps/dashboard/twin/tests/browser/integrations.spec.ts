import { expect, test } from '@playwright/test'
import { PerspectiveCamera, Vector3 } from 'three'

test('all isolated integrations render and core controls work', async ({ page }) => {
  const errors: string[] = []
  const externalRequests: string[] = []
  page.on('request', request => { if (/^https?:/.test(request.url()) && new URL(request.url()).hostname !== '127.0.0.1') externalRequests.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/lab.html')
  await expect(page.getByRole('heading', { name: 'Interface foundations' })).toBeVisible()
  await page.getByRole('button', { name: 'Open dialog', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Validate form' }).click()
  await expect(page.getByText('Enter a label', { exact: true })).toBeVisible()
  await page.getByLabel('Example label').fill('Lab fixture')
  await page.getByRole('button', { name: 'Validate form' }).click()
  await expect(page.getByText('Fixture label: Lab fixture')).toBeVisible()
  await page.getByRole('button', { name: 'Command palette', exact: true }).click()
  await page.getByPlaceholder('Find a fixture…').fill('rack-01')
  await page.getByRole('option', { name: 'rack-01' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.lab-footer')).toContainText('rack-01')
  await page.screenshot({ path: 'test-results/component-gallery.png', fullPage: true })

  await page.getByRole('button', { name: /Security tables/ }).click()
  await expect(page.getByTestId('security-grid').getByText('Compute rack 01', { exact: true })).toBeVisible()
  await page.getByLabel('Search fixture devices').fill('Survey rover')
  await expect(page.getByTestId('security-grid').getByRole('row')).toHaveCount(2)
  await page.getByTestId('security-grid').getByText('Survey rover', { exact: true }).click()
  await expect(page.locator('.lab-footer')).toContainText('rover-01')

  await page.getByRole('button', { name: /Network topology/ }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(4)
  await expect(page.locator('.react-flow__edge')).toHaveCount(3)
  await page.locator('.react-flow__node[data-id="rack-01"]').click()
  await expect(page.locator('.lab-footer')).toContainText('rack-01')

  await page.getByRole('button', { name: /Telemetry/ }).click()
  await expect(page.getByTestId('telemetry-chart').locator('canvas')).toBeVisible()
  await page.getByRole('button', { name: 'Latency', exact: true }).click()
  await expect(page.getByTestId('telemetry-chart')).toHaveAttribute('aria-label', /latency/i)

  await page.getByRole('button', { name: /Panel layout/ }).click()
  await expect(page.locator('.react-grid-item')).toHaveCount(3)
  const handle = page.locator('.react-grid-item').first().locator('.react-resizable-handle')
  const bounds = await handle.boundingBox()
  if (!bounds) throw new Error('Missing grid resize handle')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down(); await page.mouse.move(bounds.x + 70, bounds.y + 65, { steps: 12 }); await page.mouse.up()
  await expect(page.getByText('Layout interactions: 1.', { exact: false })).toBeVisible()

  await page.getByRole('button', { name: /Digital twin/ }).click()
  await expect(page.getByTestId('twin-scene').locator('canvas')).toBeVisible()
  await page.getByLabel('Postprocessing bloom').click()
  await page.getByLabel('Postprocessing bloom').click()
  await page.getByRole('button', { name: 'Reset camera' }).click()
  const scene = page.getByTestId('twin-scene').locator('canvas')
  const sceneBounds = await scene.boundingBox()
  if (!sceneBounds) throw new Error('Missing scene canvas')
  const camera = new PerspectiveCamera(45, sceneBounds.width / sceneBounds.height, 0.1, 1000)
  camera.position.set(10, 10, 12); camera.lookAt(0, 0, 0); camera.updateMatrixWorld()
  const rack = new Vector3(0, 0.9, -2).project(camera)
  await scene.click({ position: { x: (rack.x + 1) * sceneBounds.width / 2, y: (1 - rack.y) * sceneBounds.height / 2 } })
  await expect(page.locator('.lab-footer')).toContainText('rack-02')
  const beforeOrbit = await scene.screenshot()
  await page.mouse.move(sceneBounds.x + sceneBounds.width * 0.8, sceneBounds.y + sceneBounds.height * 0.75)
  await page.mouse.down(); await page.mouse.move(sceneBounds.x + sceneBounds.width * 0.65, sceneBounds.y + sceneBounds.height * 0.8, { steps: 12 }); await page.mouse.up()
  expect((await scene.screenshot()).equals(beforeOrbit)).toBe(false)
  await page.getByRole('button', { name: 'Reset camera' }).click()
  await page.screenshot({ path: 'test-results/digital-twin.png', fullPage: true })

  await page.getByRole('button', { name: /Agent integration/ }).click()
  await page.getByRole('button', { name: 'Run mock investigation' }).click()
  await expect(page.getByText('Human decision required · simulation')).toBeVisible()
  await page.getByRole('button', { name: 'Approve simulation' }).click()
  await expect(page.getByText('simulated · no actuation')).toBeVisible()
  await page.getByRole('button', { name: 'Open optional CopilotKit conversation' }).click()
  await page.getByPlaceholder('Ask about the fixture…').fill('Explain the fixture')
  await page.getByPlaceholder('Ask about the fixture…').press('Enter')
  await expect(page.getByText(/Local fixture response: cabinet contact/)).toBeVisible({ timeout: 30000 })
  await expect(page.getByRole('alert').filter({ hasText: 'Unable to render' })).toHaveCount(0)
  expect(errors).toEqual([])
  expect(externalRequests).toEqual([])
})

