import { expect, test, type Page } from '@playwright/test'

const nav = (page: Page, name: string) => page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: false })
const noOverflow = async (page: Page) => { await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth), {timeout:5000}).toBeLessThanOrEqual(1) }

test('workspace deep links, internal navigation and browser history stay synchronized', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#network')
  await expect(page.getByTestId('command-device-grid')).toBeVisible()
  await page.locator('.react-flow__node[data-id="ap-03"]').click()
  await page.getByRole('button', { name: 'Locate in digital twin' }).click()
  await expect(page).toHaveURL(/#twin$/)
  await expect(page.locator('.twin-workspace canvas')).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/#network$/)
  await expect(page.locator('.sec-device-inspect h2')).toContainText('PHANTOM-AP-03')
  await page.goForward()
  await expect(page).toHaveURL(/#twin$/)
  await page.getByRole('button', { name: 'Follow rover camera', exact: true }).click()
  await nav(page, 'Command Overview').click()
  await expect(page).toHaveURL(/#overview$/)
  await expect(page.getByRole('button', { name: 'Isometric camera', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'View all incidents', exact: true }).click()
  await expect(page).toHaveURL(/#incidents$/)
  await page.reload()
  await expect(page.getByTestId('incidents-workspace')).toBeVisible()
  await page.locator('.pc-brand').click()
  await expect(page).toHaveURL(/#overview$/)
  await page.goBack()
  await expect(page).toHaveURL(/#incidents$/)
  await expect(page.getByTestId('incidents-workspace')).toBeVisible()
  await page.goto('/#unrecognized-workspace')
  await expect(page).toHaveURL(/#overview$/)
  await expect(page.getByRole('heading', { name: 'Command overview', exact: true })).toBeVisible()
})

