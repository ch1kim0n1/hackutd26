test('spatial picking, cameras, layout editing, manual observations and incident creation work', async ({ page }) => {
  const { PerspectiveCamera, Vector3 } = await import('three')
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/')
  await page.getByRole('button',{name:'Arrange panels',exact:true}).click()
  const handle = page.getByTestId('command-grid').locator('.react-grid-item').first().locator('.react-resizable-handle')
  const bounds = await handle.boundingBox()
  if (!bounds) throw new Error('Missing resize handle')
  const item = page.getByTestId('command-grid').locator('.react-grid-item').first()
  const before = await item.boundingBox()
  await page.mouse.move(bounds.x + bounds.width/2,bounds.y + bounds.height/2)
  await page.mouse.down(); await page.mouse.move(bounds.x-90,bounds.y+60,{steps:10}); await page.mouse.up()
  const after = await item.boundingBox()
  expect(after?.width !== before?.width || after?.height !== before?.height).toBe(true)
  await page.getByRole('button',{name:'Reset layout',exact:true}).click()
  await page.getByRole('button',{name:'Lock panels',exact:true}).click()
  await nav(page,'Digital Twin').click()
  const canvas = page.locator('.twin-workspace canvas')
  await expect(canvas).toBeVisible()
  await page.getByRole('button',{name:'Reset camera',exact:true}).click()
  await page.waitForTimeout(150)
  const scene = await canvas.boundingBox()
  if (!scene) throw new Error('Missing facility canvas')
  const camera = new PerspectiveCamera(40,scene.width/scene.height,0.1,180)
  camera.position.set(36,29,17); camera.lookAt(12,0,-9); camera.updateMatrixWorld()
  const rack = new Vector3(3,1.3,-3).project(camera)
  await canvas.click({position:{x:(rack.x+1)*scene.width/2,y:(1-rack.y)*scene.height/2}})
  await expect(page.locator('.pc-footer-context')).toContainText('RACK-01')
  const iso = await canvas.screenshot()
  await page.getByRole('button',{name:'Top down camera',exact:true}).click()
  await expect(page.getByRole('button',{name:'Top down camera',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.waitForTimeout(150)
  expect((await canvas.screenshot()).equals(iso)).toBe(false)
  await page.getByRole('button',{name:'RF field',exact:true}).click()
  await expect(page.getByRole('button',{name:'RF field',exact:true})).toHaveAttribute('aria-pressed','false')
  await page.getByRole('button',{name:'Follow rover camera',exact:true}).click()
  await expect(page.getByRole('button',{name:'Follow rover camera',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'Inject event',exact:true}).click()
  await page.getByRole('menuitem',{name:'Cabinet tampering',exact:true}).click()
  await page.getByLabel('Simulation speed').selectOption('4')
  await page.getByRole('button',{name:'Start simulation',exact:true}).click()
  await nav(page,'Incident Center').click()
  await page.locator('.sec-incident-queue').getByRole('button',{name:'Create incident',exact:true}).click()
  await page.getByLabel('Incident title').fill('Operator checkpoint inspection')
  await page.getByLabel('Incident zone').selectOption('zone-network')
  await page.getByRole('dialog').getByRole('button',{name:'Create incident',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Operator checkpoint inspection',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Pause',exact:true}).click()
  await nav(page,'Rover Operations').click()
  await expect(page.locator('.pc-mission-list')).toBeVisible()
  const missions = await page.locator('.pc-mission-list>button').count()
  await page.getByRole('button',{name:/Network core B · Queue inspection waypoint/}).click()
  await expect(page.locator('.pc-mission-list>button')).toHaveCount(missions+1)
})
