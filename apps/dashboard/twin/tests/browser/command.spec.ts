test('disruptive mock actions require operator approval and emergency stop latches motion', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/')
  await page.getByLabel('Simulation scenario').selectOption('impersonation')
  await page.getByLabel('Simulation speed').selectOption('8')
  await page.getByRole('button', { name: 'Start simulation', exact: true }).click()
  await nav(page, 'Rover Operations').click()
  await page.getByRole('button', { name: 'Emergency stop', exact: true }).click()
  await expect(page.getByText('Emergency stop is latched.', { exact: true })).toBeVisible()
  const position = await page.getByRole('img',{name:/Simulated rover camera/}).getAttribute('aria-label')
  await page.waitForTimeout(700)
  expect(await page.getByRole('img',{name:/Simulated rover camera/}).getAttribute('aria-label')).toBe(position)
  await page.getByRole('button',{name:'Return home',exact:true}).click()
  await expect(page.getByText('Emergency stop is latched.', { exact: true })).toBeVisible()
  await page.getByRole('button',{name:'Release stop',exact:true}).click()
  await nav(page, 'Incident Center').click()
  const retry = page.getByRole('button',{name:'Reassign inspection',exact:true})
  // The cancelled investigation mission may need operator reassignment;
  // wait for the dossier to render it, but don't fail if the autonomous
  // flow already recovered on its own.
  await retry.waitFor({state:'visible',timeout:5000}).then(() => retry.click()).catch(() => {})
  await nav(page, 'Nemotron Intelligence').click()
  await expect(page.getByRole('button',{name:'Approve simulation',exact:true})).toBeVisible({timeout:25000})
  await page.getByRole('button',{name:'Pause',exact:true}).click()
  await page.getByRole('button',{name:'Approve simulation',exact:true}).click()
  await expect(page.getByRole('button',{name:'Approve simulation',exact:true})).toHaveCount(0)
  await expect(page.getByText('Simulated containment approved',{exact:true})).toBeVisible()
})

